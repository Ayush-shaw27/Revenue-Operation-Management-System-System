/** TypeScript types matching the FastAPI backend schemas. */

export interface User {
  id: string;
  name: string;
  email: string;
  role: 'admin' | 'manager' | 'sales-executive';
  status: string;
  last_login?: string;
  created_at?: string;
}

export interface LoginResponse {
  access_token: string;
  token_type: string;
  user: User;
}

export interface Lead {
  id: string;
  name: string;
  email: string;
  phone: string;
  company: string;
  status: string;
  source: string;
  value: number;
  industry: string;
  company_size: string;
  touchpoints: number;
  notes: string;
  created_at: string;
  ai_score?: number;
  ai_label?: string;
  ai_factors?: string[];
}

export interface Deal {
  id: string;
  title: string;
  company: string;
  value: number;
  probability: number;
  owner: string;
  close_date?: string;
  stage: string;
  ai_recommendation?: string;
  is_anomalous: boolean;
  days_in_stage: number;
  last_stage_change?: string;
  created_at: string;
}

export interface Account {
  id: string;
  name: string;
  industry: string;
  contract_value: number;
  last_activity_days: number;
  usage_trend: number;
  ticket_count: number;
  renewal_in_days: number;
  health_score: number;
}

export interface Activity {
  id: string;
  deal_id?: string;
  lead_id?: string;
  type: string;
  author: string;
  content: string;
  created_at: string;
}

export interface Alert {
  id: string;
  kind: string;
  severity: string;
  entity_type: string;
  entity_id: string;
  entity_name: string;
  summary: string;
  read: boolean;
  created_at: string;
}

export interface Notification {
  id: string;
  type: string;
  title: string;
  message: string;
  read: boolean;
  created_at: string;
}

export interface HealthResponse {
  status: string;
  version: string;
  models_loaded: boolean;
  service: string;
}

export interface ExecSummary {
  generated_at: string;
  total_pipeline_value: number;
  open_deals: number;
  closed_won_value: number;
  closed_won_count: number;
  win_rate: number;
  avg_deal_value: number;
  total_leads: number;
  high_value_deals: number;
  at_risk_accounts: number;
  leading_source: string;
  revenue_forecast_metric: number;
}

export interface LeadScoreResponse {
  score: number;
  label: string;
  conversion_probability: number;
  confidence: number;
  factors: string[];
}

export interface ForecastDataPoint {
  period: string;
  actual: number;
  traditional: number;
  mlForecast: number;
  confidence: number;
  lower_bound: number;
  upper_bound: number;
}

export interface RevenueForecastResponse {
  timeframe: string;
  model_type: string;
  accuracy: number;
  model_description: string;
  data: ForecastDataPoint[];
  traditional_total: number;
  ml_projected_total: number;
  variance_percentage: number;
  mae?: number;
  rmse?: number;
  r2?: number;
}

export interface InsightItem {
  id: string;
  type: string;
  title: string;
  description: string;
  confidence: number;
  actionable: boolean;
  metric_affected: string;
  evidence?: string;
  recommendation?: string;
}

export interface PipelineInsightsResponse {
  pipeline_health_score: number;
  win_rate_estimate: number;
  total_pipeline_value: number;
  total_deals: number;
  insights: InsightItem[];
}

export interface ChurnPrediction {
  account_id: string;
  account_name: string;
  risk_score: number;
  tier: string;
  confidence: number;
  top_factors: Array<{ factor: string; direction: string; weight: number; rank: number }>;
  model_version: string;
}

export interface AnomalyDetection {
  deal_id: string;
  deal_title: string;
  company: string;
  value: number;
  stage: string;
  days_in_stage: number;
  anomaly_score: number;
  is_anomalous: boolean;
  stalled: boolean;
  reasons: string[];
  model_version: string;
}

export interface NextBestAction {
  deal_id: string;
  deal_title: string;
  company: string;
  stage: string;
  recommendations: Array<{
    action_id: string;
    action: string;
    channel: string;
    priority: number;
    rationale: string;
    rank: number;
  }>;
}

export interface CopilotResponse {
  question: string;
  answer: string;
  /** "omniroute" when generated by the AI provider, "local-rules" for the fallback. */
  provider: string;
  model?: string | null;
  /** Explains why the provider was or was not used (e.g. missing credentials). */
  note?: string | null;
  metrics?: Record<string, unknown>;
}

export interface ModelRegistryEntry {
  name: string;
  version: string;
  trained_at: string;
  accuracy: number;
  kind: string;
  notes: string;
}

export interface AdminStats {
  system_health: number;
  api_latency_ms: number;
  requests_today: number;
  ml_inferences_today: number;
  active_users: number;
  cpu_usage: number;
  memory_usage: number;
  models_loaded: number;
  uptime_hours: number;
  total_leads: number;
  total_deals: number;
  pipeline_value: number;
}

export interface FunnelResponse {
  by: string;
  funnel: Array<{ name: string; value: number; color?: string }>;
}

export interface CohortsResponse {
  cohorts: Array<{
    cohort: string;
    total: number;
    converted: number;
    conversion_rate: number;
  }>;
}

export interface TrendPoint {
  period: string;
  revenue: number;
}

export interface ForecastScenarioResponse {
  timeframe: string;
  model_type: string;
  accuracy: number;
  model_description: string;
  data: ForecastDataPoint[];
  traditional_total: number;
  ml_projected_total: number;
  variance_percentage: number;
  scenario?: {
    discount: number;
    headcount: number;
    factor: number;
  };
}

export interface AuditLogEntry {
  id: string;
  user: string;
  action: string;
  resource: string;
  type: string;
  timestamp: string;
  ip: string;
}
